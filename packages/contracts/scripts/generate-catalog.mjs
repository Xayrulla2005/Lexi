#!/usr/bin/env node
/**
 * Generates packages/contracts/src/generated/catalog.ts from
 * legal-knowledge/catalog/problems.json (domain ids, problem ids, catalog version).
 *
 *   pnpm gen:contracts           # write the file
 *   pnpm gen:contracts --check   # exit 1 if the committed file is out of date (CI)
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "../../..");
const SOURCE = join(repoRoot, "legal-knowledge/catalog/problems.json");
const TARGET = join(here, "../src/generated/catalog.ts");

function fail(message) {
  console.error(`gen:contracts: ${message}`);
  process.exit(1);
}

const catalog = JSON.parse(readFileSync(SOURCE, "utf8"));
if (typeof catalog.versiya !== "string") fail("`versiya` must be a string");
if (!catalog.sohalar || typeof catalog.sohalar !== "object") fail("`sohalar` must be an object");
if (!Array.isArray(catalog.muammolar)) fail("`muammolar` must be an array");

const domains = Object.keys(catalog.sohalar);
for (const d of domains) if (!/^[a-z0-9_]+$/.test(d)) fail(`invalid domain id "${d}"`);

const problemIds = catalog.muammolar.map((m) => m.id);
for (const id of problemIds) if (!/^P\d{2}$/.test(id)) fail(`invalid problem id "${id}"`);
if (new Set(problemIds).size !== problemIds.length) fail("duplicate problem ids");
const sortedIds = [...problemIds].sort();

const list = (values) => values.map((v) => `  ${JSON.stringify(v)},`).join("\n");
const output = `// AUTO-GENERATED by \`pnpm gen:contracts\` from ${relative(repoRoot, SOURCE).replaceAll("\\", "/")}.
// Do not edit by hand — change the catalog and re-run the generator.

/** Catalog version (\`versiya\`). */
export const CATALOG_VERSION = ${JSON.stringify(catalog.versiya)};

/** Legal domain ids (\`sohalar\`), in catalog order. */
export const LEGAL_DOMAIN_IDS = [
${list(domains)}
] as const;

/** Problem type ids (\`muammolar[].id\`), sorted. */
export const PROBLEM_IDS = [
${list(sortedIds)}
] as const;
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(TARGET, "utf8").replace(/\r\n/g, "\n");
  } catch {
    // missing file is reported below
  }
  if (current !== output) fail(`${relative(repoRoot, TARGET)} is out of date — run \`pnpm gen:contracts\``);
  console.log(`gen:contracts: up to date (${domains.length} domains, ${sortedIds.length} problems)`);
} else {
  mkdirSync(dirname(TARGET), { recursive: true });
  writeFileSync(TARGET, output);
  console.log(`gen:contracts: wrote ${relative(repoRoot, TARGET)} (${domains.length} domains, ${sortedIds.length} problems)`);
}
