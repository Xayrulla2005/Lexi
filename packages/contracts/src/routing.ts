import { z } from "zod";
import { LegalReference } from "./analysis";
import { ProblemId } from "./classification";
import { ReviewStatus, Slug } from "./common";

/**
 * EMERGENCY  — immediate-danger escalation; always takes precedence.
 * RULE_BASED — the classified problemId matched a catalog route in packages/legal-engine.
 * FALLBACK   — no catalog route; generic advice + human review.
 */
export const RouteType = z.enum(["EMERGENCY", "RULE_BASED", "FALLBACK"]);
export type RouteType = z.infer<typeof RouteType>;

export const RouteStep = z.object({
  order: z.number().int().positive(),
  /** User-facing action text (catalog text, never generated by the AI). */
  action: z.string().min(1),
  /** Agency id from the catalog (`idoralar`); null when no single agency is involved. */
  agencyId: Slug.nullable(),
  /** Only set when the deadline is backed by a VERIFIED source. */
  deadlineDays: z.number().int().nonnegative().nullable(),
  documentTemplateId: Slug.nullable(),
});
export type RouteStep = z.infer<typeof RouteStep>;

/** Agency contact details copied verbatim from the catalog (`idoralar`). */
export const AgencyContact = z.object({
  id: Slug,
  name: z.string().min(1),
  /** Phone number(s) exactly as in the catalog; null when the catalog has none. */
  phone: z.string().min(1).nullable(),
  /** URL or app name exactly as in the catalog (not always a URL); null when none. */
  link: z.string().min(1).nullable(),
});
export type AgencyContact = z.infer<typeof AgencyContact>;

/** Produced only by the deterministic Legal Routing Engine — never by the AI. */
export const RoutingDecision = z.object({
  routeType: RouteType,
  /** Id of the matched catalog route (P01–P65) or EMERGENCY; null for FALLBACK. */
  routeId: Slug.nullable(),
  /** Catalog problem type of the route; null for EMERGENCY/FALLBACK. */
  problemId: ProblemId.nullable(),
  /** Catalog problem title (`nom`); null for EMERGENCY/FALLBACK. */
  title: z.string().min(1).nullable(),
  /** Primary agency: first route agency that is not the other party; null when none applies. */
  agencyId: Slug.nullable(),
  steps: z.array(RouteStep),
  /** Agencies of the route in catalog order (`organlar`). */
  agencies: z.array(AgencyContact),
  /** Where to go if the agencies above do not help (`eskalatsiya`). */
  escalation: z.array(AgencyContact),
  /** Laws cited by the catalog route (`qonunlar`); always DRAFT until reviewed. */
  legalReferences: z.array(LegalReference),
  /** Application template id (`shablon_id`); null when none. */
  templateId: Slug.nullable(),
  /** Legal review status of the route (legal-knowledge/catalog/review-status.json). */
  reviewStatus: ReviewStatus,
  /** User-facing warning shown whenever reviewStatus is not VERIFIED; null otherwise. */
  reviewNotice: z.string().min(1).nullable(),
  /** True whenever the route is not VERIFIED or the analysis asks for review. */
  requiresHumanReview: z.boolean(),
});
export type RoutingDecision = z.infer<typeof RoutingDecision>;
